export const NETRIN_LANGUAGE_KEY = 'netrin.language'

function getInitialLanguage() {
  if (typeof window === 'undefined') return 'zh-CN'
  try {
    const stored = window.localStorage.getItem(NETRIN_LANGUAGE_KEY)
    return stored === 'en' || stored === 'zh-CN' ? stored : 'zh-CN'
  } catch {
    return 'zh-CN'
  }
}

